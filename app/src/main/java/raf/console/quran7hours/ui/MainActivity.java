    private int findTimingIndex(int[] timings, long positionMs) {
        if (timings == null || timings.length == 0) return 0;

        int index = Arrays.binarySearch(timings, (int) positionMs);

        if (index < 0) {
            index = -index - 2;
        }

        return Math.max(0, Math.min(index, timings.length - 1));
    }

    // Определяем суру по открытой странице Корана
    private int getSuraIndexForQuranPage() {
        int page = viewPager.getCurrentItem() + 1;
        int index = 0;

        for (int i = 0; i < 114 && i < numPageSures.length; i++) {
            if (numPageSures[i] <= page) {
                index = i;
            } else {
                break;
            }
        }

        return index;
    }

    // Автоматическая прокрутка к элементу списка
    private void scrollAudioListToPosition(int position) {
        RecyclerView list = b.suraList;

        list.post(() -> {
            RecyclerView.Adapter<?> adapter = list.getAdapter();

            if (adapter == null ||
                    position < 0 ||
                    position >= adapter.getItemCount()) {
                return;
            }

            RecyclerView.LayoutManager manager = list.getLayoutManager();

            if (manager instanceof LinearLayoutManager) {
                ((LinearLayoutManager) manager)
                        .scrollToPositionWithOffset(position, 0);
            } else {
                list.scrollToPosition(position);
            }
        });
    }

    // Обновление подсветки в зависимости от позиции аудио
    private void updateAudioHighlights(boolean autoScroll) {
        if (exoPlayer == null || b == null) return;

        long positionMs = Math.max(0L, exoPlayer.getCurrentPosition());

        int suraIndex = findTimingIndex(suraTimingsMs, positionMs);
        int pageIndex = findTimingIndex(pageTimingsMs, positionMs);
        int pageNumber = pageIndex + 1;

        if (suraIndex != lastHighlightedSura) {
            lastHighlightedSura = suraIndex;

            if (suraAdapter != null) {
                suraAdapter.setCurrentPlaying(suraIndex);
            }

            if (autoScroll && b.suraRadioButton.isChecked()) {
                scrollAudioListToPosition(suraIndex);
            }
        }

        if (pageNumber != lastHighlightedPage) {
            lastHighlightedPage = pageNumber;

            if (pageAdapter != null) {
                pageAdapter.setCurrentPlaying(pageNumber);
            }

            if (autoScroll && b.pageRadioButton.isChecked()) {
                scrollAudioListToPosition(pageIndex);
            }
        }
    }

    // Прокрутка при открытии вкладки
    private void scrollToRelevantAudioItem() {
        if (b == null || exoPlayer == null) return;

        boolean hasAudioPosition =
                exoPlayer.getCurrentPosition() > 0 ||
                        exoPlayer.isPlaying();

        if (b.suraRadioButton.isChecked()) {
            int index = hasAudioPosition
                    ? findTimingIndex(
                    suraTimingsMs,
                    exoPlayer.getCurrentPosition()
            )
                    : getSuraIndexForQuranPage();

            scrollAudioListToPosition(index);

        } else if (b.pageRadioButton.isChecked()) {
            int index = hasAudioPosition
                    ? findTimingIndex(
                    pageTimingsMs,
                    exoPlayer.getCurrentPosition()
            )
                    : viewPager.getCurrentItem();

            scrollAudioListToPosition(index);
        }
    }

